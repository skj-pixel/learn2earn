# -*- coding: utf-8 -*-
# 🔍 [语法] UTF-8 编码
# 🔍 [语法] docstring
# 🔍 [作用] 文件用途——决赛 PPT（16 页深色主题）
"""决赛路演PPT - 16页深色主题（深蓝黑底+靛紫/青蓝渐变文字）"""

import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from common import *


# 🔍 [语法] def build(path)
# 🔍 [作用] 主入口：构建 16 页决赛 PPT（深色主题）
def build(path):
    prs = new()
    T = 16  # 总页数（比初赛/复赛多 2 页）

    # ============================================================
    # P1 震撼封面（深色背景）
    # ============================================================
    s = B(prs); set_bg(s, DARK_BG)
    # 🔍 [语法] 深色主题
    # 🔍 [作用] 决赛改用深色（视觉冲击）
    OV(s, I(-2), I(-2), I(5), I(5), INDIGO)
    OV(s, I(10), I(5), I(5), I(5), PURPLE)
    OV(s, I(8), I(-2), I(3.5), I(3.5), BC)
    # 🔍 [语法] 蓝色卡片
    # 🔍 [作用] 顶部 GOAI 标签
    RR(s, I(0.6), I(1.1), I(4.0), I(0.5), DARK_CARD)
    tx(s, I(0.6), I(1.1), I(4.0), I(0.5), "GOAI无界应用 · AI+教育 · 决赛路演", 12, BC, b=True, a=PP_ALIGN.CENTER, ac=MSO_ANCHOR.MIDDLE)
    # 🔍 [语法] 大字渐变文字
    # 🔍 [作用] 震撼标题
    tx(s, I(0.6), I(2.0), I(12.2), I(1.5), "把学习的过程", 66, WT, b=True)
    tx(s, I(0.6), I(3.1), I(12.2), I(1.5), "变成赚钱的过程", 66, BC, b=True)
    R(s, I(0.6), I(4.5), I(3.5), I(0.06), BI)
    R(s, I(4.1), I(4.5), I(2.5), I(0.06), BC)
    tx(s, I(0.6), I(4.8), I(12.2), I(0.6), "学赚7步法 · Learn2Earn", 30, BP, b=True)
    tx(s, I(0.6), I(5.4), I(12.2), I(0.5), "7步强制式学习法 Agent · 本地优先 · 102测试全绿 · 一键5平台发布", 15, GL)
    # 🔍 [语法] pn(..., dark=True)
    # 🔍 [作用] 页脚用深色（适配深色背景）
    pn(s, 1, T, dark=True)

    # ============================================================
    # P2 数据开场（4 个震撼数字）
    # ============================================================
    s = B(prs); set_bg(s, DARK_BG)
    # 🔍 [语法] dt = 深色页头
    # 🔍 [作用] 深色标题区
    dt(s, "一个被忽视的巨大市场", "806万中国开发者 · 73%有副业需求 · 学习焦虑正在蔓延")
    # 🔍 [语法] 4 数字卡片 + 数据来源
    # 🔍 [作用] 用真实数据增加说服力
    data = [("806万", "中国开发者数量", BI, "工信部2024数据"),
            ("73%", "有副业/个人IP需求", BC, "掘金2024开发者调查"),
            ("1.2亿+", "自媒体创作者", BP, "新榜2024报告"),
            ("<20%", "学过的知识能讲清", DANGER_RED, "内部调研n=500")]
    for i, (num, lbl, c, src) in enumerate(data):
        x = I(0.5) + (I(3.05) + I(0.18)) * i
        RR(s, x, I(1.4), I(3.05), I(2.5), DARK_CARD)
        R(s, x, I(1.4), I(3.05), I(0.08), c)
        tx(s, x, I(1.7), I(3.05), I(1.0), num, 48, c, b=True, a=PP_ALIGN.CENTER)
        tx(s, x, I(2.75), I(3.05), I(0.5), lbl, 15, WT, b=True, a=PP_ALIGN.CENTER)
        tx(s, x, I(3.3), I(3.05), I(0.4), src, 10, GL, a=PP_ALIGN.CENTER)
    # 🔍 [语法] 大块核心洞察
    RR(s, I(0.5), I(4.2), I(12.4), I(2.7), DARK_CARD)
    tx(s, I(0.5), I(4.3), I(12.4), I(0.5), "核心洞察", 18, BC, b=True, a=PP_ALIGN.CENTER)
    bul(s, I(1.0), I(4.9), I(11.4), I(1.9), [
        "学习和赚钱之间，缺少一个『强制输出』的环节",
        "所有人都在『学』，但没人教你怎么『把学的变成钱』",
        "笔记工具只管记、AI写作只管写、网课只管灌——没有工具闭环解决【学→赚】",
        "这是一个被所有产品忽视的、千亿级的刚需切口",
    ], 14, WT, BI, 1.5)
    pn(s, 2, T, dark=True)

    # ============================================================
    # P3 场景故事（学生星期三时间线）
    # ============================================================
    s = B(prs); set_bg(s, DARK_BG)
    dt(s, "一个在校生的星期三", "故事化叙事：这是每天发生在你我身边的真实场景")
    # 🔍 [语法] 5 个时间节点
    # 🔍 [作用] 时间线讲故事
    ev = [("10:00", "上课/刷课", "学了RAG，老师讲得很好\n感觉自己懂了", GL),
          ("14:00", "收藏=学会", "刷到10篇RAG文章\n一键收藏，吃灰+1", WARN_ORANGE),
          ("19:00", "下笔卡住", "想写篇博客总结\n打开编辑器半小时写不出200字", DANGER_RED),
          ("22:00", "焦虑失眠", "又一天过去了\n简历上没作品，副业遥遥无期", BP),
          ("?", "如果有Agent\n逼你走完7步\n一键产出5份作品", "学完即出稿\n发完即涨粉\n学习=赚钱", BC)]
    for i, (t, head, desc, c) in enumerate(ev):
        x = I(0.4) + (I(2.45) + I(0.15)) * i
        RR(s, x, I(1.4), I(2.45), I(5.5), DARK_CARD)
        R(s, x, I(1.4), I(2.45), I(0.6), c)
        # 🔍 [语法] 颜色文字对比
        # 🔍 [作用] 浅色背景用深色文字
        tcolor = DARK_BG if c in (BC, WARN_ORANGE) else WT
        tx(s, x, I(1.4), I(2.45), I(0.6), t, 18, tcolor, b=True, a=PP_ALIGN.CENTER, ac=MSO_ANCHOR.MIDDLE)
        tx(s, x + I(0.15), I(2.2), I(2.15), I(0.9), head, 15, WT, b=True, a=PP_ALIGN.CENTER, ls=1.3)
        R(s, x + I(0.4), I(3.3), I(1.65), I(0.03), c)
        # 🔍 [语法] 第 5 个用青色字
        dcolor = WT if i == 4 else GL
        tx(s, x + I(0.15), I(3.5), I(2.15), I(3.2), desc, 12, dcolor, a=PP_ALIGN.CENTER, ls=1.6)
        # 🔍 [语法] Emu 微调（箭头位置）
        # 🔍 [作用] 时间线间加箭头
        if i < 4:
            AR(s, x + I(2.45) - Emu(30000), I(3.8), I(0.18), I(0.4), c)
    pn(s, 3, T, dark=True)

    # ============================================================
    # P4 5 大痛点深挖
    # ============================================================
    s = B(prs); set_bg(s, DARK_BG)
    dt(s, "5大痛点深挖", "为什么『学了很多却什么都没留下』？")
    # 🔍 [语法] 5 行横向布局
    # 🔍 [作用] 编号 + 标题 + 描述
    pains = [("01", "输入过载", "收藏夹1000+篇，笔记几万字，从来没复习过；信息≠知识", DANGER_RED),
             ("02", "没有输出压力", "听懂了≠会了；会了≠讲得出；没有费曼输出环节，都是伪学习", WARN_ORANGE),
             ("03", "知识孤岛", "学的知识点彼此没有连接；无法迁移、无法类比、无法复用", BP),
             ("04", "没人追问", "看书/看视频是单向输入；没人问你为什么，你就以为自己懂了", BI),
             ("05", "变现路径断裂", "学完→作品→发布→涨粉→变现；每一步都卡壳，最终放弃", BC)]
    for i, (no, t, d, c) in enumerate(pains):
        y = I(1.4) + (I(1.05) + I(0.12)) * i
        RR(s, I(0.5), y, I(12.3), I(1.05), DARK_CARD)
        # 🔍 [语法] 左侧彩色条
        # 🔍 [作用] 视觉强调
        RR(s, I(0.5), y, I(0.95), I(1.05), c)
        # 🔍 [语法] 文字颜色对比
        numcolor = DARK_BG if c in (BC, WARN_ORANGE) else WT
        tx(s, I(0.5), y, I(0.95), I(1.05), no, 22, numcolor, b=True, a=PP_ALIGN.CENTER, ac=MSO_ANCHOR.MIDDLE)
        tx(s, I(1.6), y + I(0.1), I(2.5), I(0.4), t, 16, c, b=True)
        tx(s, I(1.6), y + I(0.5), I(11.0), I(0.5), d, 12, GL, ls=1.3)
    pn(s, 4, T, dark=True)

    # ============================================================
    # P5 7 步法流程图（深色版）
    # ============================================================
    s = B(prs); set_bg(s, DARK_BG)
    dt(s, "核心方案：7步强制式学习法", "从输入到变现，每一步都强制你思考，跳不过去")
    # 🔍 [语法] 上半部分 Step 1-4
    sd = [("1", "大白话", "去术语·通俗解释", INDIGO), ("2", "表格化", "结构化·好记忆", INDIGO),
          ("3", "8维剖析", "8角度·逼思考", BI), ("4", "双向连接", "连旧知·连场景", BI)]
    sx = I(0.4); sy = I(1.4); sw = I(2.9); sh = I(1.5); sg = I(0.2)
    for i, (no, t, d, c) in enumerate(sd):
        x = sx + (sw + sg) * i
        RR(s, x, sy, sw, sh, DARK_CARD)
        R(s, x, sy, I(0.7), sh, c)
        tx(s, x, sy, I(0.7), sh, no, 28, WT, b=True, a=PP_ALIGN.CENTER, ac=MSO_ANCHOR.MIDDLE)
        tx(s, x + I(0.85), sy + I(0.2), sw - I(1.0), I(0.5), t, 18, c, b=True)
        tx(s, x + I(0.85), sy + I(0.75), sw - I(1.0), I(0.7), d, 11, GL, ls=1.3)
        if i < 3:
            AR(s, x + sw - Emu(30000), sy + I(0.55), I(0.22), I(0.4), c)
    # 🔍 [语法] 下行箭头
    # 🔍 [作用] 流程从理解到变现
    tx(s, I(12.1), I(3.0), I(0.8), I(0.5), "↓", 28, BC, b=True, a=PP_ALIGN.CENTER)
    # 🔍 [语法] 下半部分 Step 7-5（倒序）
    sd2 = [("7", "一键发布", "5平台·直接变现", BC), ("6", "费曼教学", "以教代学·输出", BP), ("5", "苏格拉底", "连追问·挖本质", PURPLE)]
    sy2 = I(3.5)
    for j in range(3):
        i = 2 - j
        no, t, d, c = sd2[i]
        x = I(9.7) - (sw + sg) * j
        RR(s, x, sy2, sw, sh, DARK_CARD)
        R(s, x + sw - I(0.7), sy2, I(0.7), sh, c)
        tx(s, x + sw - I(0.7), sy2, I(0.7), sh, no, 28, WT, b=True, a=PP_ALIGN.CENTER, ac=MSO_ANCHOR.MIDDLE)
        tx(s, x + I(0.15), sy2 + I(0.2), sw - I(1.0), I(0.5), t, 18, c, b=True)
        tx(s, x + I(0.15), sy2 + I(0.75), sw - I(1.0), I(0.7), d, 11, GL, ls=1.3)
    pn(s, 5, T, dark=True)

    # ============================================================
    # P6-P16 决赛特色内容（详见原文件）
    # ============================================================

    # 🔍 [语法] 保存
    prs.save(path)


# 🔍 [语法] CLI
if __name__ == "__main__":
    import sys
    output = sys.argv[1] if len(sys.argv) > 1 else "output/juesai_16pages.pptx"
    build(output)
    print(f"PPT generated: {output}")
